#!/usr/bin/env python3
"""Generate the Simulink data contract: bus types plus a port manifest.

Usage: generate_types.py <sysml> <outdir>

The generated half of the Simulink seam is the interface only: one
``Simulink.Bus`` per distinct port definition (``defineBusTypes.m``) and the
machine-readable counterpart the drift oracle reads (``ports.json``). The model
itself is hand-authored in ``hand_model.m`` and is never written here.

Values in ``ports.json`` are rendered MATLAB literals (``2``, ``true``,
``'text'``) or ``null``; an array field is rendered as a bracketed vector. The
same fixture and the same inputs produce byte-identical files.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from pyfmi_sysml import architecture, components

BUS_DATA_TYPE = {
    "Real": "double",
    "Integer": "int32",
    "Boolean": "boolean",
    "String": "string",
}

HEADER = "% Generated by generate_types.py \u2014 do not edit.\n"


def matlab_literal(type_name: str, text: str | None) -> str | None:
    """MATLAB spelling of one authored value, or ``None`` when unbound."""
    if text is None:
        return None
    if type_name == "String":
        return "'" + text.replace("'", "''") + "'"
    if type_name == "Boolean":
        return "true" if text.strip().lower() in ("true", "1") else "false"
    return text


def field_value(
    field, starts: dict[str, str | None], prefix: str = ""
) -> str | None:
    """One field's value from its FMI member expressions."""
    values = [starts.get(prefix + member) for _, member in field.members()]
    literals = [matlab_literal(field.type_name, value) for value in values]
    if any(literal is None for literal in literals):
        return None
    if field.array is None:
        return literals[0]
    return "[" + ", ".join(literals) + "]"


def bus_definitions(component_list) -> dict[str, tuple]:
    """Distinct port definitions, rejecting a definition that disagrees."""
    definitions: dict[str, tuple] = {}
    for component in component_list:
        for port in component.ports:
            known = definitions.get(port.definition)
            if known is not None and known != port.fields:
                raise ValueError(
                    f"port definition {port.definition} disagrees between usages"
                )
            definitions[port.definition] = port.fields
    return definitions


def render_bus_types(bus_fields: dict[str, tuple], source: str) -> str:
    lines = [HEADER, f"% Bus types for {source}.\n"]
    for name in sorted(bus_fields):
        lines.append(f"\n{name} = Simulink.Bus;\n")
        lines.append(f"{name}.Elements = Simulink.BusElement;\n")
        for index, field in enumerate(bus_fields[name], start=1):
            lines.append(f"{name}.Elements({index}).Name = '{field.name}';\n")
            lines.append(
                f"{name}.Elements({index}).DataType = "
                f"'{BUS_DATA_TYPE[field.type_name]}';\n"
            )
            if field.array is not None:
                lines.append(
                    f"{name}.Elements({index}).Dimensions = '[{field.array}]';\n"
                )
    return "".join(lines)


def render_manifest(component_list) -> dict[str, object]:
    manifest: dict[str, object] = {}
    for component in sorted(component_list, key=lambda item: item.name):
        starts = {
            variable.member: variable.start_text for variable in component.variables
        }
        ports = []
        for port in sorted(component.ports, key=lambda item: item.name):
            ports.append(
                {
                    "name": port.name,
                    "direction": port.direction,
                    "bus": port.definition,
                    "fields": [
                        {
                            "name": field.name,
                            "type": field.type_name,
                            "value": field_value(field, starts, port.name + "."),
                        }
                        for field in port.fields
                    ],
                }
            )
        parameters = []
        for field in sorted(component.parameters, key=lambda item: item.name):
            value = field_value(field, starts)
            parameters.append(
                {
                    "name": field.name,
                    "type": field.type_name,
                    "value": value,
                    "unbound": value is None,
                }
            )
        manifest[component.name] = {"ports": ports, "parameters": parameters}
    return manifest


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(f"usage: {argv[0]} <sysml> <outdir>", file=sys.stderr)
        return 2
    source = Path(argv[1])
    outdir = Path(argv[2])
    outdir.mkdir(parents=True, exist_ok=True)

    component_list = list(components(architecture(source)))
    bus_fields = bus_definitions(component_list)

    bus_path = outdir / "defineBusTypes.m"
    bus_path.write_text(
        render_bus_types(bus_fields, source.name), encoding="utf-8", newline="\n"
    )
    print(f"wrote {bus_path}")

    manifest_path = outdir / "ports.json"
    manifest_path.write_text(
        json.dumps(render_manifest(component_list), indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
